"""Общото за имената на улици и спирки: кавичките, думите "ул."/"бул." и сравнението на две имена."""

import functools
import re

QUOTES = "'\"‘’“”„«»`´"

ADDRESS_WORDS = {"булевард": "бул.", "бул": "бул.", "улица": "ул.", "ул": "ул.", "площад": "площад", "пл": "площад"}

# Думите в името, които не го различават от другите: "бул. Княгиня Мария Луиза" и "Мария Луиза"
IGNORED_WORDS = {
    "УЛ", "БУЛ", "ПЛ", "УЛИЦА", "БУЛЕВАРД", "ПЛОЩАД", "МЕТРОСТАНЦИЯ", "МЕТРО", "СПИРКА", "ЖП", "КН", "Ж", "К", "ГР", "КВ",
}


@functools.lru_cache(maxsize=8192)
def name_words(name: str) -> frozenset[str]:
    """Различаващите думи от името с големи букви: "бул. Княгиня Мария Луиза" -> {КНЯГИНЯ, МАРИЯ, ЛУИЗА}."""
    words = re.findall(r"\w+", name.upper())
    return frozenset(word for word in words if word not in IGNORED_WORDS)
